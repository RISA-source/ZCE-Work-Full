"""
encode_networks.py
==================
Loads trained weights, encodes each network as a v2 ZCE bitstream,
writes raw byte files + a C header with the streams embedded.
"""

import numpy as np
import sys
sys.path.insert(0, '/home/claude')
from zce_ml_encoder import encode_mlp_forward_v2

def leaky_relu(x, alpha=0.01):
    return np.where(x > 0, x, alpha * x)

def forward_np(X, W1, b1, W2, b2):
    h   = leaky_relu(X @ W1.T + b1)
    out = h @ W2.T + b2
    return np.argmax(out, axis=1)

def encode_and_verify(name, W1, b1, W2, b2, X_test, y_test, max_samples=20):
    """Encode network, compute numpy predictions, write stream."""
    # Use up to max_samples for the stream (all predictions embedded)
    X_sub  = X_test[:max_samples]
    y_sub  = y_test[:max_samples]
    np_pred = forward_np(X_sub, W1, b1, W2, b2)

    stream = encode_mlp_forward_v2(W1, b1, W2, b2, X_sub, activation='leaky_relu')

    path = f'/home/claude/stream_{name}.zce'
    with open(path, 'wb') as f:
        f.write(stream)

    print(f"\n[{name}]")
    print(f"  Architecture: {W1.shape[1]}-in → {W1.shape[0]}-hidden → {W2.shape[0]}-out")
    print(f"  Samples encoded: {len(X_sub)}")
    print(f"  Stream size: {len(stream)} bytes ({len(stream)*8} bits)")
    print(f"  numpy preds: {np_pred.tolist()}")
    print(f"  true labels: {y_sub.tolist()}")
    print(f"  numpy acc:   {(np_pred == y_sub).mean():.3f}")

    return stream, np_pred.tolist(), y_sub.tolist()

def make_c_header(networks):
    """Generate a C header embedding all streams + expected predictions."""
    lines = [
        '/* zce_test_streams.h — auto-generated by encode_networks.py */',
        '#ifndef ZCE_TEST_STREAMS_H',
        '#define ZCE_TEST_STREAMS_H',
        '#include <stdint.h>',
        '',
    ]

    for name, stream, np_preds, true_labels in networks:
        hex_vals = ', '.join(f'0x{b:02x}' for b in stream)
        lines += [
            f'/* ── {name} ─────────────────────────────── */',
            f'static const uint8_t ZCE_STREAM_{name.upper()}[] = {{',
            f'    {hex_vals}',
            f'}};',
            f'static const int ZCE_STREAM_{name.upper()}_LEN = {len(stream)};',
            f'static const int ZCE_NPRED_{name.upper()}[] = {{',
            f'    {", ".join(str(p) for p in np_preds)}',
            f'}};',
            f'static const int ZCE_TRUE_{name.upper()}[] = {{',
            f'    {", ".join(str(l) for l in true_labels)}',
            f'}};',
            f'static const int ZCE_NSAMPLES_{name.upper()} = {len(np_preds)};',
            '',
        ]

    lines += ['#endif /* ZCE_TEST_STREAMS_H */']
    return '\n'.join(lines)

if __name__ == '__main__':
    d = np.load('/home/claude/trained_weights.npz')
    MAX = 20  # samples per network

    networks = []

    s, p, t = encode_and_verify('iris',
        d['W1_i'], d['b1_i'], d['W2_i'], d['b2_i'],
        d['X_te_i'], d['y_te_i'], MAX)
    networks.append(('iris', s, p, t))

    s, p, t = encode_and_verify('moons',
        d['W1_m'], d['b1_m'], d['W2_m'], d['b2_m'],
        d['X_te_m'], d['y_te_m'], MAX)
    networks.append(('moons', s, p, t))

    s, p, t = encode_and_verify('blobs',
        d['W1_b'], d['b1_b'], d['W2_b'], d['b2_b'],
        d['X_te_b'], d['y_te_b'], MAX)
    networks.append(('blobs', s, p, t))

    header = make_c_header(networks)
    with open('/home/claude/zce_test_streams.h', 'w') as f:
        f.write(header)
    print(f"\nWrote zce_test_streams.h ({len(header)} chars)")
